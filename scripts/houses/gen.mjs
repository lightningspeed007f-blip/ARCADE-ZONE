// Write laststand/js/housedata.js from the bakes in ./out, and copy the models to laststand/assets/models/houses.
import fs from 'fs';
import { CONFIG } from './config.mjs';
const OUT = process.env.OUT || './out', ROOT = new URL('../../laststand/', import.meta.url).pathname;
let out = `// Generated by scripts/houses (see assets/README.md, "Walk-in houses"). Do not edit by hand: re-bake instead.
// Per house, in its own frame (metres; front faces -z, front edge on z = 0, centred on x):
//   foot [x0, z0, x1, z1]  what you see, from above     top  its height
//   boxes [cx, cz, hx, hz, y0, y1, slab?]   walls, floors, steps up to head height (slab: a thin floor zombies may path over)
//   spots [x, y, z]  open floor inside, for loot and for people waiting indoors
//   doors {x, z, along, w, h, y, out, open?}   floors [x0, z0, x1, z1, y]  a floor (and ceiling) drawn by the game
export const HOUSE_DATA = {\n`;
for (const n of Object.keys(CONFIG)) {
  const b = JSON.parse(fs.readFileSync(`${OUT}/${n}.bake.json`)); delete b.name;
  b.doors = b.doors.map((d) => { const o = { x: d.x, z: d.z, along: d.along, w: d.w, h: d.h, y: d.y || 0, out: d.out || -1 }; if (d.open) o.open = true; return o; });
  out += `  ${n}: ${JSON.stringify(b)},\n`;
  fs.copyFileSync(`${OUT}/${n}.glb`, `${ROOT}assets/models/houses/${n}.glb`);
}
fs.writeFileSync(`${ROOT}js/housedata.js`, out + '};\n');
console.log('wrote', `${ROOT}js/housedata.js`);
